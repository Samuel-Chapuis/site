function applyLanguageCv(lang) {
  const activeLang = cvTranslations[lang] ? lang : "fr";
  const html = document.documentElement;
  const langToggle = document.getElementById("langToggleCv");

  html.lang = activeLang;
  localStorage.setItem("siteLanguage", activeLang);

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.getAttribute("data-i18n");
    const translation = cvTranslations[activeLang][key];

    if (translation) {
      element.textContent = translation;
    }
  });

  if (langToggle) {
    const flagSrc = activeLang === "fr" ? "img/Flag_France.png" : "img/Flag_United_Kingdom.png";
    const alt = activeLang === "fr" ? "FR" : "EN";
    langToggle.innerHTML = `<img src="${flagSrc}" alt="${alt}" class="flag-icon" />`;
    langToggle.setAttribute("aria-label", activeLang === "en" ? "Passer en français" : "Switch to English");
  }
}

document.addEventListener("DOMContentLoaded", () => {
  const storedLang = localStorage.getItem("siteLanguage") || "fr";
  applyLanguageCv(storedLang);

  const langToggle = document.getElementById("langToggleCv");

  if (langToggle) {
    langToggle.addEventListener("click", () => {
      const currentLang = document.documentElement.lang || "fr";
      const nextLang = currentLang === "en" ? "fr" : "en";
      applyLanguageCv(nextLang);
    });
  }
});
